#!/usr/bin/env python3
"""Convert a Lottie .json into a C source file for lv_lottie_set_src_data().

usage: python lottie_to_c.py anim.json [symbol_name] > src/lottie/anim.c
Minifies the JSON and appends the NUL terminator LVGL requires.
"""
import json, sys

def main():
    path = sys.argv[1]
    name = sys.argv[2] if len(sys.argv) > 2 else "lottie_anim"
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    blob = json.dumps(data, separators=(",", ":")).encode("utf-8") + b"\0"
    w, h = data.get("w"), data.get("h")
    fr, ip, op = data.get("fr"), data.get("ip"), data.get("op")
    out = []
    out.append("/* generated by lottie_to_c.py from %s */" % path.replace("\\", "/").split("/")[-1])
    out.append("/* %sx%s px, %s fps, frames %s..%s, %d bytes incl. NUL */" % (w, h, fr, ip, op, len(blob)))
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("const uint8_t %s[] = {" % name)
    for i in range(0, len(blob), 16):
        out.append("    " + ",".join("0x%02x" % b for b in blob[i:i+16]) + ",")
    out.append("};")
    out.append("const size_t %s_size = sizeof(%s);" % (name, name))
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("%s: %d bytes, %sx%s, %s fps, %s frames\n" % (name, len(blob), w, h, fr, (op or 0) - (ip or 0)))

main()
